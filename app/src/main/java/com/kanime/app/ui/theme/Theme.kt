@Composable
private fun animateColor(target: Color): Color {
    if (LocalInspectionMode.current) return target
    return animateColorAsState(
        targetValue = target,
        animationSpec = tween(durationMillis = 220),
        label = "ThemeColorFade"
    ).value
}

