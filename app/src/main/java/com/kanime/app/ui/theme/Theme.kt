@Composable
fun KAnimeTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    updateSystemBars: Boolean = true,
    animateTransition: Boolean = true,
    content: @Composable () -> Unit
) {
    val targetScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkKanimeColorScheme
        else -> LightKanimeColorScheme
    }

    val colorScheme = if (animateTransition) targetScheme.animated() else targetScheme
    val reducedTransparency = rememberReducedTransparency()
    val glassTokens = remember(colorScheme, darkTheme, reducedTransparency) {
        kanimeGlassTokensFor(
            colorScheme = colorScheme,
            isDark = darkTheme,
            reducedTransparency = reducedTransparency
        )
    }
    val windowSize = rememberKanimeWindowSize()

    val view = LocalView.current
    if (updateSystemBars && !view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window
            window?.let {
                val insetsController = WindowCompat.getInsetsController(it, view)
                insetsController.isAppearanceLightStatusBars = !darkTheme
                insetsController.isAppearanceLightNavigationBars = !darkTheme
                it.decorView.setBackgroundColor(targetScheme.background.toArgb())
            }
        }
    }

    CompositionLocalProvider(
        LocalKanimeGlass provides glassTokens,
        LocalWindowSizeClass provides windowSize
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = KanimeShapes,
            content = content
        )
    }
}
